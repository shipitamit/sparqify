"""CI helper:  sparqix ci-comment OUTDIR [--max-chars N]

Reads OUTDIR/SPARQIX_REPORT.json (written by `sparqix project`) and writes OUTDIR/comment.md (a pull-request comment with a
hidden marker so the action can update it in place). When running in GitHub Actions it also sets step outputs and appends the
comment to the job summary."""
from __future__ import annotations

import json
import os

MARKER = "<!-- sparqix-report -->"
ICON = {"OK": "✅", "CHECK": "⚠️", "NEEDS REVIEW": "🛠️", "FAILED": "❌"}


def md(text, limit: int = 300) -> str:
    """Untrusted text (file names, converter messages quoting the input) -> inert Markdown: one line, no HTML, links, mentions or issue refs."""
    t = "".join(c if c.isprintable() else " " for c in str(text))
    t = " ".join(t.split())[:limit]
    t = t.replace("\u200b", "").replace("@", "@\u200b")        # a zero-width space defuses @mentions without showing a backslash
    return "".join("\\" + c if c in "\\`*_{}[]<>()#+-!|~:&" else c for c in t)


def code(text, limit: int = 200) -> str:
    """inline code span that the text cannot break out of"""
    t = " ".join("".join(c if c.isprintable() else " " for c in str(text)).split())[:limit]
    return "`" + t.replace("`", "'").replace("|", "/") + "`"


def build_comment(data: dict, max_chars: int = 60000, title: str = "Sparqix conversion report") -> tuple[str, dict]:
    files = data.get("files", [])
    cnt = {k: sum(f["status"] == k for f in files) for k in ("OK", "CHECK", "NEEDS REVIEW", "FAILED")}
    todos = sum(len(f["todos"]) for f in files)
    warns = sum(len(f["warnings"]) for f in files)
    stats = {"converted": len(files), "ok": cnt["OK"], "check": cnt["CHECK"], "needs_review": cnt["NEEDS REVIEW"],
             "failed": cnt["FAILED"], "todos": todos, "warnings": warns, "skipped": len(data.get("skipped", []))}
    L = [MARKER, f"### {title}", ""]
    if not files:
        L += ["No convertible files found in this change.", ""]
    else:
        L += [f"**{len(files)}** file(s) converted: ✅ {cnt['OK']} ok · ⚠️ {cnt['CHECK']} with warnings · "
              f"🛠️ {cnt['NEEDS REVIEW']} need manual review · ❌ {cnt['FAILED']} failed — **{todos}** TODO(s), **{warns}** warning(s).", ""]
        order = ["FAILED", "NEEDS REVIEW", "CHECK", "OK"]
        rows = sorted(files, key=lambda f: (order.index(f["status"]), f["rel"]))
        L += ["| File | Type | Output | Status | TODOs | Warnings |", "|---|---|---|---|---|---|"]
        for f in rows[:60]:
            L.append(f"| {code(f['rel'])} | {md(f['lang'])} | {code(f['out'] or '-')} | {ICON.get(f['status'], '')} {md(f['status'])} | {len(f['todos'])} | {len(f['warnings'])} |")
        if len(rows) > 60:
            L.append(f"| … | | | | | {len(rows) - 60} more file(s) in the report artifact |")
        detail = [f for f in rows if f["todos"] or f["warnings"]]
        if detail:
            L += ["", "<details><summary>TODOs and warnings</summary>", ""]
            for f in detail:
                L += [f"**{code(f['rel'])}**", ""]
                L += [f"- 🛠️ TODO ({md(t[0], 60)}): {md(t[1])}" for t in f["todos"][:25]]
                L += [f"- ⚠️ ({md(w[0], 60)}): {md(w[1])}" for w in f["warnings"][:15]]
                L.append("")
            L += ["</details>"]
    if data.get("skipped"):
        L += ["", f"<sub>{len(data['skipped'])} file(s) skipped (not code or handled by `sparqix orchestrate`).</sub>"]
    L += ["", "<sub>Generated by sparqix. Conversions are a starting point: review the TODOs and run `sparqix verify` on sample data.</sub>"]
    text = "\n".join(L) + "\n"
    if len(text) > max_chars:
        text = text[:max_chars].rsplit("\n", 1)[0] + "\n\n_(truncated: see the uploaded report artifact for everything)_\n</details>\n"
    return text, stats


def relativize(changed: list, path: str) -> list:
    """repo-relative changed files -> paths relative to the converted folder (files outside it are dropped)"""
    base = os.path.normpath(path).replace("\\", "/")
    out = []
    for f in changed:
        f = f.strip().replace("\\", "/")
        if not f:
            continue
        if base in (".", ""):
            out.append(f)
        elif f.startswith(base + "/"):
            out.append(f[len(base) + 1:])
    return out


def changed_main(argv) -> int:
    import argparse
    p = argparse.ArgumentParser(prog="sparqix ci-changed")
    p.add_argument("--path", default=".")
    p.add_argument("--list", required=True, help="file with repo-relative changed paths")
    p.add_argument("--out", required=True)
    a = p.parse_args(argv)
    with open(a.list, encoding="utf-8") as fh:
        rel = relativize(fh.read().splitlines(), a.path)
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(rel) + ("\n" if rel else ""))
    print(len(rel))
    return 0


def main(argv) -> int:
    import argparse
    p = argparse.ArgumentParser(prog="sparqix ci-comment")
    p.add_argument("outdir")
    p.add_argument("--max-chars", type=int, default=60000)
    p.add_argument("--title", default="Sparqix conversion report")
    a = p.parse_args(argv)
    with open(os.path.join(a.outdir, "SPARQIX_REPORT.json"), encoding="utf-8") as fh:
        data = json.load(fh)
    text, stats = build_comment(data, a.max_chars, a.title)
    path = os.path.join(a.outdir, "comment.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    out = os.environ.get("GITHUB_OUTPUT")
    if out:
        with open(out, "a", encoding="utf-8") as fh:
            for k, v in {**stats, "comment_path": path, "report_path": os.path.join(a.outdir, "SPARQIX_REPORT.md")}.items():
                fh.write(f"{k}={v}\n")
    summ = os.environ.get("GITHUB_STEP_SUMMARY")
    if summ:
        with open(summ, "a", encoding="utf-8") as fh:
            fh.write(text.replace(MARKER, "") + "\n")
    print(json.dumps(stats))
    return 0
